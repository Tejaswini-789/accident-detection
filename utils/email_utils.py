"""
utils/email_utils.py - SMTP email alert sender
"""
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text     import MIMEText
from email.mime.image    import MIMEImage
from pathlib import Path
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from config import EMAIL_SENDER, EMAIL_PASSWORD, EMAIL_RECEIVER, SMTP_HOST, SMTP_PORT


def send_alert_email(
    accident_id: int,
    source_name: str,
    source_type: str,
    timestamp: str,
    confidence: float,
    severity: str,
    snapshot_path: str = None,
    location: str = "Not configured",
    recipient: str = None,
) -> tuple:
    """
    Send an accident alert email with optional snapshot attachment.
    Returns (success: bool, message: str).
    """
    to_addr = recipient or EMAIL_RECEIVER
    if not (EMAIL_SENDER and EMAIL_PASSWORD and to_addr):
        return False, "Email credentials not configured. Set ALERT_EMAIL_SENDER, ALERT_EMAIL_PASSWORD, ALERT_EMAIL_RECEIVER in environment or Settings."

    subject = f"🚨 Accident Alert #{accident_id} — {severity} Severity"
    body_html = f"""
    <html><body style="font-family:Arial,sans-serif;background:#1a1a2e;color:#eee;padding:20px;">
    <div style="max-width:600px;margin:auto;background:#16213e;border-radius:12px;padding:24px;">
      <h2 style="color:#e94560;">🚨 Road Accident Detected</h2>
      <table style="width:100%;border-collapse:collapse;">
        <tr><td style="padding:8px;color:#aaa;">Accident ID</td><td style="padding:8px;">#{accident_id}</td></tr>
        <tr style="background:#0f3460;"><td style="padding:8px;color:#aaa;">Source</td><td style="padding:8px;">{source_name} ({source_type})</td></tr>
        <tr><td style="padding:8px;color:#aaa;">Time</td><td style="padding:8px;">{timestamp}</td></tr>
        <tr style="background:#0f3460;"><td style="padding:8px;color:#aaa;">Confidence</td><td style="padding:8px;">{confidence:.1%}</td></tr>
        <tr><td style="padding:8px;color:#aaa;">Severity</td><td style="padding:8px;font-weight:bold;color:#e94560;">{severity}</td></tr>
        <tr style="background:#0f3460;"><td style="padding:8px;color:#aaa;">Location</td><td style="padding:8px;">{location}</td></tr>
      </table>
      {"<p>📸 Snapshot attached below.</p>" if snapshot_path else ""}
      <p style="color:#888;font-size:12px;margin-top:20px;">
        This alert was generated by the AI Road Accident Detection System. 
        Please dispatch emergency services immediately if confirmed.
      </p>
    </div>
    </body></html>
    """

    msg = MIMEMultipart("related")
    msg["Subject"] = subject
    msg["From"]    = EMAIL_SENDER
    msg["To"]      = to_addr
    msg.attach(MIMEText(body_html, "html"))

    if snapshot_path and Path(snapshot_path).exists():
        with open(snapshot_path, "rb") as f:
            img = MIMEImage(f.read(), name=Path(snapshot_path).name)
        msg.attach(img)

    try:
        with smtplib.SMTP(SMTP_HOST, SMTP_PORT, timeout=15) as srv:
            srv.ehlo()
            srv.starttls()
            srv.login(EMAIL_SENDER, EMAIL_PASSWORD)
            srv.sendmail(EMAIL_SENDER, to_addr, msg.as_string())
        return True, f"Alert sent to {to_addr}"
    except smtplib.SMTPAuthenticationError:
        return False, "SMTP authentication failed. Check email and app password."
    except smtplib.SMTPException as e:
        return False, f"SMTP error: {e}"
    except Exception as e:
        return False, f"Unexpected error: {e}"
